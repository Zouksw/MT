describe("parseComexRows (round-163)", () => {
	it("extracts China monthly rows and derives USD/ton from the sums", () => {
		const rows = parseComexRows(FIXTURE_2026, 2026);
		const boneless = rows.filter((r) => r.code === "02023000");
		expect(boneless).toHaveLength(7); // Jan..Jul
		const jan = boneless.find((r) => r.period === "2026-01");
		expect(jan).toBeDefined();
		expect(jan?.valueUsd).toBeCloseTo(91_212_893, 0);
		expect(jan?.quantityKg).toBeCloseTo(17_478_069, 0);
		// 91,212,892.98 / 17,478.06881 t ≈ 5,219 USD/t (the upsert rounds at 6dp).
		expect(Math.round((jan!.valueUsd / jan!.quantityKg) * 1000)).toBe(5219);

		// The HS6 aggregate layer mirrors the (single) NCM child exactly.
		const hs6 = rows.find((r) => r.code === "020230" && r.period === "2026-01");
		expect(hs6?.level).toBe("HS6");
		expect(hs6?.valueUsd).toBeCloseTo(91_212_893, 0);

		// The HS4 layer rolls up every frozen NCM of the year's response set.
		const hs4 = rows.find((r) => r.code === "0202" && r.period === "2026-01");
		expect(hs4?.level).toBe("HS4");
		expect(hs4?.valueUsd).toBeCloseTo(91_212_893, 0); // single-product fixture
	});

	it("aggregates sibling NCMs under one HS6 by summing amount+weight", () => {
		const rows = parseComexRows(FIXTURE_2025, 2025);
		const ncms = new Set(rows.filter((r) => r.level === "NCM8").map((r) => r.code));
		expect(ncms.has("02022010")).toBe(true);
		expect(ncms.has("02022020")).toBe(true);
		expect(ncms.has("02022090")).toBe(true);
		// Nonexistent/unknown codes in the response are ignored, never landed.
		expect(ncms.has("02062900")).toBe(false);

		const hs4 = rows.filter((r) => r.level === "HS4" && r.code === "0202");
		expect(hs4.length).toBeGreaterThan(0);
		const hs = rows.filter((r) => r.level === "HS6" && r.code === "020220");
		const ncmRows = rows.filter((r) => r.level === "NCM8" && r.code.startsWith("020220"));
		expect(hs.length).toBeGreaterThan(0);
		for (const h of hs) {
			const siblings = ncmRows.filter((n) => n.period === h.period);
			expect(h.valueUsd).toBeCloseTo(
				siblings.reduce((s, n) => s + n.valueUsd, 0),
				6,
			);
			expect(h.quantityKg).toBeCloseTo(
				siblings.reduce((s, n) => s + n.quantityKg, 0),
				6,
			);
		}
	});

	it("skips confidential zero rows, non-China rows and malformed months", () => {
		const rows = parseComexRows(FIXTURE_2026, 2026);
		// Albania's confidential zero rows never survive.
		expect(rows.every((r) => r.valueUsd > 0 && r.quantityKg > 0)).toBe(true);
		expect(parseComexRows([], 2026)).toEqual([]);
		expect(
			parseComexRows(
				[{ product: { id: "02023000" }, country: { iso2: "CN" }, month: 13, amount: 1, weight: 1 }],
				2026,
			),
		).toEqual([]);
	});
});

